// Helper to generate realistic historical candlestick bars for a symbol given base price and trend
export function generateCandlestickHistory(
  basePrice: number,
  volatilityPct: number = 0.015,
  count: number = 60,
  upwardBias: number = 0.001
): CandlestickPoint[] {
  const bars: CandlestickPoint[] = [];
  let currentPrice = basePrice * 0.92;
  const now = Date.now();
  const stepMs = 3600 * 1000 * 4; // 4 hour bars

  for (let i = count - 1; i >= 0; i--) {
    const timeTimestamp = now - i * stepMs;
    const dateObj = new Date(timeTimestamp);
    const timeLabel = dateObj.toLocaleDateString('en-US', { month: 'short', day: 'numeric', hour: '2-digit' });
    
    // random delta
    const delta = (Math.random() - 0.48 + upwardBias) * volatilityPct * currentPrice;
    const open = currentPrice;
    const close = Math.max(open * 0.5, open + delta);
    const highWick = Math.random() * volatilityPct * 0.8 * open;
    const lowWick = Math.random() * volatilityPct * 0.8 * open;
    const high = Math.max(open, close) + highWick;
    const low = Math.min(open, close) - lowWick;
    const volume = Math.floor(basePrice * 1200 + Math.random() * basePrice * 3500);

    bars.push({
      time: timeLabel,
      timestamp: timeTimestamp,
      open: Number(open.toFixed(2)),
      high: Number(high.toFixed(2)),
      low: Number(low.toFixed(2)),
      close: Number(close.toFixed(2)),
      volume,
    });

    currentPrice = close;
  }

  // Ensure last bar close matches the current price
  if (bars.length > 0) {
    bars[bars.length - 1].close = basePrice;
    bars[bars.length - 1].high = Math.max(bars[bars.length - 1].high, basePrice);
    bars[bars.length - 1].low = Math.min(bars[bars.length - 1].low, basePrice);
  }

  return bars;
}

export function generateSparkline(history: CandlestickPoint[]): number[] {
  if (history.length <= 15) {
    return history.map(h => h.close);
  }
  const step = Math.floor(history.length / 14);
  const result: number[] = [];
  for (let i = 0; i < history.length; i += step) {
    result.push(history[i].close);
  }
  if (result[result.length - 1] !== history[history.length - 1].close) {
    result.push(history[history.length - 1].close);
  }
  return result;
}

